def test_create_webhook_with_autogenerated_secret(client: TestClient, auth_headers):
    payload = {
        "url": "https://erp.provedor.com.br/api/v1/webhooks/oltapi",
        "description": "ERP IXC Soft Matriz",
        "events": ["onu.reconciled", "onu.detected"],
    }
    response = client.post("/api/v1/webhooks", json=payload, headers=auth_headers)
    assert response.status_code == 201
    data = response.json()

    assert data["url"] == "https://erp.provedor.com.br/api/v1/webhooks/oltapi"
    assert data["description"] == "ERP IXC Soft Matriz"
    assert data["events"] == ["onu.reconciled", "onu.detected"]
    assert data["secret"].startswith("whsec_")
    assert "Location" in response.headers
    assert response.headers["Location"] == f"/api/v1/webhooks/{data['id']}"
    assert "_links" in data
    assert "ping" in data["_links"]


